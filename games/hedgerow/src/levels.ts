/** A steady climb of `n` waves: vans, drones and (from wave `truckFrom`) trucks, growing a little each time. */
function ramp(
  n: number,
  o: {
    v: number;
    d: number;
    t?: number;
    truckFrom?: number;
    vs?: number;
    ds?: number;
    i?: number;
    infFrom?: number;
    b?: number;
    bFrom?: number;
    p?: number;
    pFrom?: number;
    e?: number;
    eFrom?: number;
    l?: number;
    lFrom?: number;
  },
): WaveGroup[][] {
  return Array.from({ length: n }, (_, i) => {
    const groups = [
      van(Math.round(o.v + i * (o.vs ?? 1.2)), Math.max(0.9, 1.9 - i * 0.1)),
    ];
    groups.push(
      drone(
        Math.round(o.d + i * (o.ds ?? 1.4)),
        Math.max(0.5, 0.95 - i * 0.05),
        2,
      ),
    );
    if (o.t && i >= (o.truckFrom ?? 2))
      groups.push(
        truck(Math.round(o.t + (i - (o.truckFrom ?? 2)) * 0.8), 2.2, 4),
      );
    if (o.i && i >= (o.infFrom ?? 1))
      groups.push(
        influencer(Math.round(o.i + (i - (o.infFrom ?? 1)) * 0.5), 2.6, 3),
      );
    if (o.b && i >= (o.bFrom ?? 1))
      groups.push(
        bulldozer(Math.round(o.b + (i - (o.bFrom ?? 1)) * 0.6), 3, 5),
      );
    if (o.p && i >= (o.pFrom ?? 1))
      groups.push(
        phantom(Math.round(o.p + (i - (o.pFrom ?? 1)) * 0.5), 2.4, 6),
      );
    if (o.e && i >= (o.eFrom ?? 1))
      groups.push(tender(Math.round(o.e + (i - (o.eFrom ?? 1)) * 0.5), 2.8, 7));
    if (o.l && i >= (o.lFrom ?? 1))
      groups.push(lawyer(Math.round(o.l + (i - (o.lFrom ?? 1)) * 0.5), 2.6, 8));
    return groups;
  });
}

